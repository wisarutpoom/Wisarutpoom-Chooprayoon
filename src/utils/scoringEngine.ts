function getScoreLevel(score: number): { level: ScoreLevel; label: string } {
  if (score >= 80) return { level: 'HIGH', label: 'โดดเด่นมาก (High Potential)' };
  if (score >= 68) return { level: 'GOOD', label: 'แข็งแกร่ง (Strong Fit)' };
  if (score >= 55) return { level: 'MODERATE', label: 'ปานกลาง (Developing)' };
  return { level: 'DEVELOP', label: 'ควรเสริมทักษะ (Needs Coaching)' };
}

function calculateDimensionPercentage(
  dimension:
    | MBTIDimensionKey
    | BigFiveDimensionKey
    | DISCDimensionKey
    | EQAQDimensionKey
    | RIASECDimensionKey
    | EnneagramDimensionKey
    | CompetencyDimensionKey,
  answers: Record<number, number>
): number {
  const items = ASSESSMENT_QUESTIONS.filter((q) => q.dimension === dimension);
  if (items.length === 0) return 50;

  let totalPoints = 0;
  items.forEach((item) => {
    const raw = answers[item.id] ?? 3;
    const aligned = item.direction === 1 ? raw : 6 - raw; // 1..5
    totalPoints += aligned;
  });

  const minPoints = items.length * 1;
  const maxPoints = items.length * 5;
  const percentage = ((totalPoints - minPoints) / (maxPoints - minPoints)) * 100;
  return Math.round(Math.max(0, Math.min(100, percentage)));
}

