export function generateAssessmentReport(
  candidate: CandidateProfile,
  answers: Record<number, number>
): AssessmentReport {
  const mbti = buildMBTIResult(answers);
  const bigFive = buildBigFiveAnalysis(answers);
  const disc = buildDISCAnalysis(answers);
  const eqAq = buildEQAQAnalysis(answers);
  const riasecDrive = buildRIASECDriveAnalysis(answers);
  const enneagram = buildEnneagramAnalysis(answers);
  const competencies = buildCompetencyAnalysis(answers);

  const avgBigFive = Math.round(bigFive.reduce((sum, c) => sum + c.score, 0) / bigFive.length);
  const avgDISC = Math.round(
    (disc.scores.D + disc.scores.I + disc.scores.S + disc.scores.C) / 4
  );
  const avgEQAQ = Math.round(eqAq.reduce((sum, c) => sum + c.score, 0) / eqAq.length);
  const avgRIASEC = Math.round(
    riasecDrive.reduce((sum, c) => sum + c.score, 0) / riasecDrive.length
  );
  const avgCompetency = Math.round(
    competencies.reduce((sum, c) => sum + c.score, 0) / competencies.length
  );

  // Weighted overall suitability score across all frameworks
  const overallScore = Math.round(
    avgCompetency * 0.35 +
      avgEQAQ * 0.2 +
      avgRIASEC * 0.15 +
      avgBigFive * 0.15 +
      avgDISC * 0.15
  );

  const { level: suitabilityLevel } = getScoreLevel(overallScore);

  const roleTracks = buildRoleTracks(mbti, bigFive, disc, eqAq, riasecDrive, competencies);
  const topTrack = roleTracks[0];
  const roadmap = build90DayRoadmap(competencies, topTrack);

  const sortedStrengths = [...competencies].sort((a, b) => b.score - a.score);
  const topComp = sortedStrengths[0];
  const weakestComp = sortedStrengths[sortedStrengths.length - 1];

  let suitabilityHeadline = '';
  let suitabilitySummary = '';

  if (overallScore >= 80) {
    suitabilityHeadline = 'ศักยภาพระดับดาวรุ่ง (High-Potential Insurance & Financial Advisor)';
    suitabilitySummary = `คุณ ${candidate.firstName} (${candidate.nickname}) มีความพร้อมรอบด้านในระดับสูงมาก ทั้งบุคลิกภาพ (${mbti.code} / DISC-${disc.blendCode} / ${enneagram.wingCode}), ความอึดทางใจ (EQ/AQ ${avgEQAQ}%) และสมรรถนะวิชาชีพ (${avgCompetency}%) มีความโดดเด่นที่สุดในด้าน "${topComp.title}" และเหมาะสมอย่างยิ่งที่จะเติบโตในเส้นทาง "${topTrack.title}"`;
  } else if (overallScore >= 68) {
    suitabilityHeadline = 'มีความเหมาะสมสูง พร้อมเติบโตเป็นตัวแทนมืออาชีพ (Strong Career Fit)';
    suitabilitySummary = `คุณ ${candidate.firstName} (${candidate.nickname}) มีพื้นฐานบุคลิกภาพ (${mbti.code} / DISC-${disc.blendCode}) และทัศนคติที่สอดคล้องกับวิชาชีพตัวแทนประกันชีวิตเป็นอย่างดี จุดแข็งหลักคือ "${topComp.title}" หากได้รับการเสริมทักษะเพิ่มเติมในด้าน "${weakestComp.title}" จะสามารถสร้างผลงานที่โดดเด่นในสาย "${topTrack.title}" ได้อย่างรวดเร็ว`;
  } else if (overallScore >= 55) {
    suitabilityHeadline = 'มีศักยภาพในการพัฒนาภายใต้ระบบพี่เลี้ยง (Developing Advisor Fit)';
    suitabilitySummary = `คุณ ${candidate.firstName} (${candidate.nickname}) มีจุดเด่นเฉพาะตัวตามโปรไฟล์ ${mbti.code} (DISC-${disc.blendCode}) และมีต้นทุนที่ดีในด้าน "${topComp.title}" แนะนำให้เริ่มต้นทำงานร่วมกับผู้จัดการหน่วยอย่างใกล้ชิด (Joint Field Work) และมุ่งเน้นการฝึกฝนทักษะ "${weakestComp.title}" ในช่วง 90 วันแรก`;
  } else {
    suitabilityHeadline = 'ควรปูพื้นฐานทักษะการขายและเสริมสร้างความมั่นใจก่อนลงสนามจริง (Foundation Coaching Required)';
    suitabilitySummary = `คุณ ${candidate.firstName} (${candidate.nickname}) มีบุคลิกภาพแบบ ${mbti.code} ซึ่งมีข้อดีด้านความตั้งใจ แต่ยังต้องได้รับการปูพื้นฐานด้านกระบวนการขาย การเปิดตลาด และการรับมือกับคำปฏิเสธอย่างเป็นขั้นตอน แนะนำให้เข้าโปรแกรมฝึกอบรมเข้มข้นและออกตลาดคู่กับพี่เลี้ยงในระยะเริ่มต้น`;
  }

  const eqScore = eqAq.find((item) => item.key === 'EQ_EMOTIONAL')?.score ?? 50;
  const aqScore = eqAq.find((item) => item.key === 'AQ_ADVERSITY')?.score ?? 50;

  const oneLineSummary = `${mbti.code} • DISC ${disc.blendCode} • ${enneagram.wingCode} | เด่นเรื่อง${topComp.title.split(' (')[0]} (${topComp.score}%) • EQ ${eqScore}% / AQ ${aqScore}% • เหมาะกับสาย ${topTrack.englishTitle.replace(' Track', '')}`;

  const completedAt =
    candidate.completedAt ||
    new Date().toLocaleDateString('th-TH', {
      year: 'numeric',
      month: 'short',
      day: 'numeric',
      hour: '2-digit',
      minute: '2-digit',
    });

  return {
    id: candidate.id,
    candidate: {
      ...candidate,
      completedAt,
    },
    overallScore,
    suitabilityLevel,
    suitabilityHeadline,
    suitabilitySummary,
    oneLineSummary,
    mbti,
    bigFive,
    disc,
    eqAq,
    riasecDrive,
    enneagram,
    competencies,
    roleTracks,
    roadmap,
    answers,
  };
}
