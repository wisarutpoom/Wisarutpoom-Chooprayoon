function buildEnneagramAnalysis(answers: Record<number, number>): EnneagramResult {
  const keys: EnneagramDimensionKey[] = [
    'ENNEAGRAM_1',
    'ENNEAGRAM_2',
    'ENNEAGRAM_3',
    'ENNEAGRAM_4',
    'ENNEAGRAM_5',
    'ENNEAGRAM_6',
    'ENNEAGRAM_7',
    'ENNEAGRAM_8',
    'ENNEAGRAM_9',
  ];

  const shortLabels: Record<number, string> = {
    1: 'Type 1 มาตรฐานถูกต้อง',
    2: 'Type 2 ผู้ให้และใส่ใจ',
    3: 'Type 3 มุ่งความสำเร็จ',
    4: 'Type 4 คุณค่าเฉพาะตัว',
    5: 'Type 5 ผู้เชี่ยวชาญข้อมูล',
    6: 'Type 6 นักจัดการความเสี่ยง',
    7: 'Type 7 นักสร้างโอกาสใหม่',
    8: 'Type 8 ผู้นำผู้ปกป้อง',
    9: 'Type 9 ผู้สร้างความสบายใจ',
  };

  const scores = keys.map((key, idx) => {
    const typeNumber = idx + 1;
    return {
      typeNumber,
      label: shortLabels[typeNumber],
      score: calculateDimensionPercentage(key, answers),
    };
  });

  const sorted = [...scores].sort((a, b) => b.score - a.score);
  const dominantType = sorted[0].typeNumber;

  const leftNeighbor = dominantType === 1 ? 9 : dominantType - 1;
  const rightNeighbor = dominantType === 9 ? 1 : dominantType + 1;
  const leftScore = scores.find((s) => s.typeNumber === leftNeighbor)?.score ?? 50;
  const rightScore = scores.find((s) => s.typeNumber === rightNeighbor)?.score ?? 50;
  const wing = leftScore >= rightScore ? leftNeighbor : rightNeighbor;
  const wingCode = `Type ${dominantType}w${wing}`;

  const info = ENNEAGRAM_INFO[dominantType] || ENNEAGRAM_INFO[3];

  return {
    dominantType,
    wingCode,
    title: info.title,
    coreMotivation: info.coreMotivation,
    insuranceStrength: info.insuranceStrength,
    insuranceCaution: info.insuranceCaution,
    coachingAdvice: info.coachingAdvice,
    scores,
  };
}

